def classify_text(text):
    prompt = f"""
Classify the following text into exactly one category:
Technical, Education, Business, Personal, Other.

Also classify sentiment as Positive, Negative, or Neutral.

Return these fields:
Category:
Sentiment:
Reason:

Text:
{text}
"""
    return generate_response(prompt, max_new_tokens=100)["response"]


