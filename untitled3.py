def coding_assistant(task, language="Python"):
    prompt = f"""
Act as a programming tutor.

Language: {language}
Task: {task}

Provide:
1. A concise explanation of the approach.
2. A code example.
3. Time and space complexity when meaningful.
4. Edge cases to test.
5. Any assumptions or limitations.

Use readable code. Do not claim code was executed or tested unless
it was actually executed.
"""
    return generate_response(prompt, max_new_tokens=320)["response"]


