def extract_json(text):
    prompt = f"""
Extract information from the input.

Return one JSON object with these keys:
{{
  "summary": "string",
  "category": "Technical, Education, Business, Personal, or Other",
  "sentiment": "Positive, Negative, or Neutral",
  "keywords": ["string"],
  "uncertain_information": ["string"]
}}

Rules:
- Use only information supported by the input.
- Do not invent missing information.
- Return valid JSON only, without Markdown code fences.

Input:
{text}
"""
    raw = generate_response(prompt, max_new_tokens=180)["response"]

    # Attempt to parse the model output.
    try:
        match = re.search(r"\{.*\}", raw, flags=re.DOTALL)
        if not match:
            raise ValueError("No JSON object found.")

        parsed = json.loads(match.group(0))

        required_keys = {
            "summary", "category", "sentiment",
            "keywords", "uncertain_information"
        }

        if not required_keys.issubset(parsed.keys()):
            raise ValueError("Required JSON keys are missing.")

        if not isinstance(parsed["keywords"], list):
            raise ValueError("'keywords' must be a list.")

        if not isinstance(parsed["uncertain_information"], list):
            raise ValueError("'uncertain_information' must be a list.")

        return {
            "valid": True,
            "data": parsed,
            "raw_output": raw
        }

    except (ValueError, json.JSONDecodeError) as error:
        return {
            "valid": False,
            "data": None,
            "raw_output": raw,
            "error": str(error)
        }


