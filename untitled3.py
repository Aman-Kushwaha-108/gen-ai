def research_assistant(topic, context=""):
    prompt = f"""
Act as a research planning assistant.

Topic: {topic}
Provided context: {context if context else "No source material provided."}

Return:
1. A concise overview based on available knowledge.
2. Key concepts to investigate.
3. Questions that need verification.
4. Suggested search queries.
5. Limitations and uncertainties.

Do not invent citations, papers, URLs, or research findings.
Clearly distinguish general knowledge from information that needs
independent verification.
"""
    return generate_response(prompt, max_new_tokens=300)["response"]


