# 7. Debugging assistant
# --------------------------------------------------

def debugging_assistant(code, error_message, language="Python"):
    prompt = f"""
Act as a careful debugging assistant.

Language: {language}

Code:
{code}

Error message:
{error_message}

Tasks:
1. Identify the likely cause.
2. Explain the bug.
3. Provide corrected code.
4. Explain why the correction works.
5. Suggest a test case.

Do not assume the code has been executed.
If the error information is insufficient, state your assumptions.
"""
    return generate_response(prompt, max_new_tokens=320)["response"]


