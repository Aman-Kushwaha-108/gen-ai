# 3. Resume improvement assistant
# --------------------------------------------------

def resume_assistant(resume_text, target_role):
    prompt = f"""
Act as a resume editor.

Target role: {target_role}

Improve the resume text for clarity, relevance, and professional tone.
Use concise bullet points where appropriate.
Do not invent employers, dates, qualifications, skills, or achievements.
If measurable results are missing, suggest where the user could add
genuine metrics rather than fabricating them.

Original resume:
{resume_text}

Return:
1. Improved profile summary
2. Improved experience or project bullets
3. Relevant skills to highlight
4. Information the user should verify
"""
    return generate_response(prompt, max_new_tokens=300)["response"]


