def summarize_text(text, length="short"):
    prompt = f"""
Summarize the source text below.

Desired length: {length}
Requirements:
- Preserve the main ideas and important facts.
- Do not introduce facts that are absent from the source.
- Mention uncertainty if the source is unclear.

Source text:
{text}

Summary:
"""
    return generate_response(prompt, max_new_tokens=220)["response"]


# --------------------------------------------------
# 2. Professional email assistant
# --------------------------------------------------

def email_assistant(
    purpose,
    recipient="Hiring Manager",
    tone="Professional",
    details=""
):
    prompt = f"""
Write a {tone.lower()} email.

Recipient: {recipient}
Purpose: {purpose}
Details provided by the user: {details}

Requirements:
- Add an appropriate subject line.
- Use a clear greeting and closing.
- Do not invent experience, qualifications, or promises.
- Keep the email concise.
- Return the subject and email body.
"""
    return generate_response(prompt, max_new_tokens=220)["response"]


