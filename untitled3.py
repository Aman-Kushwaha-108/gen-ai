def run_workflow(_):
    with tool_output:
        clear_output(wait=True)

        user_input = input_box.value.strip()
        context = context_box.value.strip()
        workflow = task_dropdown.value

        if not user_input:
            print("Please enter some input.")
            return

        try:
            if workflow == "Summarize text":
                result = summarize_text(user_input)

            elif workflow == "Write an email":
                result = email_assistant(
                    purpose=user_input,
                    recipient=context or "Hiring Manager"
                )

            elif workflow == "Improve a resume":
                result = resume_assistant(
                    user_input,
                    context or "Entry-level internship"
                )

            elif workflow == "Classify text":
                result = classify_text(user_input)

            elif workflow == "Extract JSON":
                result = extract_json(user_input)
                result = json.dumps(
                    result, indent=2, ensure_ascii=False
                )

            elif workflow == "Coding assistant":
                result = coding_assistant(
                    user_input,
                    language=context or "Python"
                )

            elif workflow == "Debug code":
                result = debugging_assistant(
                    code=user_input,
                    error_message=context or "Error message not provided"
                )

            else:
                result = research_assistant(
                    user_input,
                    context=context
                )

            display(Markdown("### Result"))
            print(result)

        except Exception as error:
            print("Workflow error:", str(error))

run_button.on_click(run_workflow)

